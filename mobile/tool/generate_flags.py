def fold(text: str) -> str:
    text = unicodedata.normalize("NFKD", text).replace("œ", "oe").replace("æ", "ae")
    text = "".join(char for char in text if not unicodedata.combining(char))
    return re.sub(r"[^a-z0-9]+", " ", text.lower()).strip()


def main() -> None:
    rows = json.loads(COUNTRIES.read_text())
    missing = [row["fr"][0] for row in rows if row["fr"][0] not in SPECS]
    if missing:
        raise SystemExit("pays sans drapeau : " + ", ".join(missing))
    flags: dict[str, str] = {}
    for row in rows:
        spec = SPECS[row["fr"][0]]
        for name in row["fr"] + row["en"]:
            flags[fold(name)] = spec
    lines = [
        "// Généré par mobile/tool/generate_flags.py. Ne pas modifier à la main.",
        "",
        "/// Nom de pays normalisé -> motif de drapeau.",
        "const countryFlagSpecs = <String, String>{",
    ]
    for key in sorted(flags):
        lines.append(f"  {json.dumps(key, ensure_ascii=False)}: {json.dumps(flags[key])},")
    lines.append("};")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"{len(flags)} noms, {len(SPECS)} drapeaux")


if __name__ == "__main__":
    main()
